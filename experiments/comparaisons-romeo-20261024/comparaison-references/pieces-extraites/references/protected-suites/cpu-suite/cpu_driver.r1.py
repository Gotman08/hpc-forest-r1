"""Protected inputs, correctness and native wall-clock timing for CPU cases."""
from pathlib import Path
import ctypes as ct,json,sys,os,math,hashlib,base64
os.environ.update(OPENBLAS_NUM_THREADS='1',MKL_NUM_THREADS='1',OMP_DYNAMIC='FALSE')
import numpy as np
R=Path(__file__).resolve().parent
CASES={c['id']:c for c in json.loads((R/'cases.json').read_text())}
PROTO=ct.CFUNCTYPE(None,ct.c_void_p,ct.c_void_p,ct.c_void_p,ct.c_int,ct.c_int,ct.c_int)
def lib(path):
    dll=ct.CDLL(str(Path(path).resolve()),mode=os.RTLD_LOCAL)
    f=PROTO(('run',dll));f._dll=dll;return f
def aligned(a):
    a=np.asarray(a);raw=np.full(a.nbytes+256,0xA7,dtype=np.uint8)
    offset=(-raw.ctypes.data)%64+32
    offset=(offset+63)//64*64
    view=raw[offset:offset+a.nbytes].view(a.dtype).reshape(a.shape);view[:]=a
    return raw,view
def dataset(name,n,seed,pattern=0):
    rng=np.random.default_rng(seed);b=np.zeros(16,dtype=np.float32);dtype=np.float32;size=n
    if name=='popcount':a=rng.integers(0,2**32,size=n,dtype=np.uint32);dtype=np.uint32;size=1
    elif name=='argmin':
        a=rng.integers(-2**30,2**30,n,dtype=np.int32)
        if pattern==1:a=np.arange(n,0,-1,dtype=np.int32)
        if pattern==2:a.fill(7)
        if pattern==3:a[:]=-1;a[-1]=np.iinfo(np.int32).min()
        if pattern==4:a.fill(np.iinfo(np.int32).max)
        dtype=np.int32;size=1
    elif name in ('blackscholes','binomial'):
        a=np.array([rng.uniform(60,140,n),rng.uniform(60,140,n),rng.uniform(.2,3,n),rng.uniform(.01,.07,n),rng.uniform(.15,.8,n)],dtype=np.float32)
        if pattern==0:a[:]=np.array([100,98,2,.02,5],dtype=np.float32)[:,None]
    elif name in ('noise','mandelbrot'):
        a=np.array([-10,-10,10,10] if name=='noise' else [-2,-1,1,1],dtype=np.float32)
        if pattern:a+=np.float32((seed%7)*.001)
        size=n*n if name=='noise' else n*n*3//2;dtype=np.int32 if name=='mandelbrot' else np.float32
    elif name=='stencil3d':a=rng.uniform(-.1,.1,n**3).astype('f4');b=rng.uniform(.01,.1,n**3).astype('f4');size=2*n**3
    elif name=='gemm_cpu':a=rng.uniform(-1,1,n*n).astype('f4');b=rng.uniform(-1,1,n*n).astype('f4');size=n*n
    elif name=='base64':
        data=(R/'reference/fastbase64/images/standard_test_images/lena_color_512.base64').read_bytes() if n==141020 and pattern==0 else base64.b64encode(rng.bytes((n//4)*3))
        a=np.frombuffer(data,dtype=np.uint8).copy();n=len(a);size=n+64;dtype=np.uint8
    elif name=='utf8':
        # Same length-class probabilities as upstream populate_utf8. The exact
        # libc random sequence is not portable; seed and generated bytes are saved.
        data=bytearray()
        while len(data)<n:
            w=int(rng.integers(256))
            code=32 if w<128 else int(rng.integers(0x80,0x800)) if w<224 else int(rng.integers(0x800,0xd800)) if w<240 else int(rng.integers(0x10000,0x110000))
            x=chr(code).encode('utf8')
            if len(data)+len(x)>n:data.extend(b' '*(n-len(data)));break
            data.extend(x)
        if pattern==1:data[:min(n,2)]=b'\xc2A'[:min(n,2)]
        if pattern==2:data[-1:]=b'\xff'
        if pattern==3:data[:]=b'a'*n
        a=np.frombuffer(bytes(data),dtype=np.uint8).copy();size=1;dtype=np.uint32
    else:raise ValueError(name)
    return a,b,np.zeros(size,dtype=dtype),n
def run_case(name,binary,n,seed,threads,benchmark=False,pattern=0):
    c=CASES[name];allowed=sorted(os.sched_getaffinity(0));os.sched_setaffinity(0,allowed[:threads])
    a,b,out,n=dataset(name,n,seed,pattern);ra,a=aligned(a);rb,b=aligned(b);rc,out=aligned(out)
    initial_a=ra.copy();initial_b=rb.copy();initial_c=rc.copy()
    f=lib(binary);ref=lib(R/'cases'/name/'naive.so')
    expected=np.zeros_like(out);param=c['parameter']
    if name=='popcount':
        val=0
        for _ in range(param):
            for item in a:val=(val+(int(item)^val).bit_count())&0xffffffff
        expected[0]=val
    elif name=='argmin':expected[0]=np.argmin(a)
    elif name=='utf8':
        try:a.tobytes().decode('utf8','strict');expected[0]=1
        except UnicodeDecodeError:expected[0]=0
    elif name=='base64':
        decoded=base64.b64decode(a.tobytes(),validate=True);expected[:8]=np.frombuffer(len(decoded).to_bytes(8,'little'),dtype='u1');expected[16:16+len(decoded)]=np.frombuffer(decoded,dtype='u1')
    elif name=='gemm_cpu':expected[:]=(a.reshape(n,n).astype('f8')@b.reshape(n,n).astype('f8')).astype('f4').ravel()
    else:ref(a.ctypes.data,b.ctypes.data,expected.ctypes.data,n,param,threads)
    f(a.ctypes.data,b.ctypes.data,out.ctypes.data,n,param,threads)
    input_ok=np.array_equal(ra,initial_a) and np.array_equal(rb,initial_b)
    offset=out.ctypes.data-rc.ctypes.data
    guards=np.array_equal(rc[:offset],initial_c[:offset]) and np.array_equal(rc[offset+out.nbytes:],initial_c[offset+out.nbytes:])
    if name=='base64':
        count=int.from_bytes(out[:8].tobytes(),'little');want=int.from_bytes(expected[:8].tobytes(),'little')
        good=count==want and np.array_equal(out[16:16+want],expected[16:16+want]);errors=int(not good);maxerr=0
    elif np.issubdtype(out.dtype,np.integer):errors=int(np.count_nonzero(out!=expected));maxerr=float(np.max(np.abs(out.astype('f8')-expected)))
    else:
        atol,rtol=(.001,.00005) if name in ('blackscholes','binomial') else (.002,.00005) if name=='gemm_cpu' else (.00005,.00005)
        delta=np.abs(out.astype('f8')-expected);errors=int(np.count_nonzero(~np.isfinite(out)|(delta>atol+rtol*np.abs(expected))));maxerr=float(delta.max())
    correct=errors==0 and input_ok and guards
    row={'case_id':name,'binary':str(binary),'n':n,'seed':seed,'pattern':pattern,'threads':threads,'affinity':sorted(os.sched_getaffinity(0)),'correct':correct,'errors':errors,'input_unchanged':bool(input_ok),'guards':bool(guards),'max_abs_error':maxerr,'input_sha256':hashlib.sha256(a.tobytes()+b.tobytes()).hexdigest()}
    if benchmark and correct:
        timer=ct.CDLL(str(R/'build/timing.so'));timer.timed.restype=ct.c_double;timer.timed.argtypes=[PROTO,ct.c_void_p,ct.c_void_p,ct.c_void_p,ct.c_int,ct.c_int,ct.c_int,ct.c_int,ct.c_int]
        trial=timer.timed(f,a.ctypes.data,b.ctypes.data,out.ctypes.data,n,param,threads,1,2)
        reps=max(1,min(100000,math.ceil(.1/max(trial,1e-9))))
        seconds=timer.timed(f,a.ctypes.data,b.ctypes.data,out.ctypes.data,n,param,threads,reps,1)
        row.update(seconds=seconds,repetitions=reps,warmups=3,metric='native_wall_seconds')
    return row
if __name__=='__main__':
    row=run_case(sys.argv[1],sys.argv[2],int(sys.argv[3]),int(sys.argv[4]),int(sys.argv[5]),sys.argv[6]=='bench',int(sys.argv[7]) if len(sys.argv)>7 else 0)
    print(json.dumps(row));sys.exit(0 if row['correct'] else 1)
